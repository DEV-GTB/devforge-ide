#!/usr/bin/env node

/**
 * DevForge IDE - Environment Setup Script
 * Run this script to create your .env file with your API keys
 */

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout,
});

const question = (prompt) => new Promise((resolve) => rl.question(prompt, resolve));

async function setupEnv() {
  console.log('\n🚀 DevForge IDE - Environment Setup\n');
  console.log('This script will help you configure your .env file with API keys.\n');

  const envPath = path.join(process.cwd(), '.env');

  // Check if .env already exists
  if (fs.existsSync(envPath)) {
    console.log('⚠️  .env file already exists.');
    const overwrite = await question('Do you want to overwrite it? (y/n): ');
    if (overwrite.toLowerCase() !== 'y') {
      console.log('Setup cancelled.');
      rl.close();
      return;
    }
  }

  console.log('\n📝 AI Provider Configuration');
  console.log('Available providers: groq, huggingface, openrouter, together');
  const provider = await question('Select AI provider (default: groq): ') || 'groq';

  console.log('\n🔑 API Keys Configuration');
  console.log('You can leave these blank if not using that provider.\n');

  const groqKey = await question('Groq API Key (or press Enter to skip): ');
  const hfKey = await question('Hugging Face API Key (or press Enter to skip): ');
  const openrouterKey = await question('OpenRouter API Key (or press Enter to skip): ');
  const togetherKey = await question('Together AI API Key (or press Enter to skip): ');

  console.log('\n🤖 Model Selection');
  const modelOptions = {
    groq: ['llama-3.3-70b-versatile', 'llama-3.1-8b-instant', 'mixtral-8x7b-32768'],
    huggingface: ['mistralai/Mistral-7B-Instruct-v0.2', 'mistralai/Mistral-7B-Instruct-v0.3', 'meta-llama/Llama-2-7b-chat-hf'],
    openrouter: ['mistralai/mistral-7b-instruct', 'meta-llama/llama-3-8b-instruct'],
    together: ['mistralai/Mistral-7B-Instruct-v0.2', 'Qwen/Qwen1.5-7B-Chat'],
  };

  const availableModels = modelOptions[provider] || modelOptions.groq;
  console.log(`Available models for ${provider}:`);
  availableModels.forEach((m, i) => console.log(`  ${i + 1}. ${m}`));

  const modelIndex = await question(`Select model (1-${availableModels.length}, default: 1): `);
  const model = availableModels[(parseInt(modelIndex) - 1) || 0] || availableModels[0];

  console.log('\n🎙️  TTS Configuration');
  console.log('Available providers: browser (free), elevenlabs');
  const ttsProvider = await question('Select TTS provider (default: browser): ') || 'browser';

  const elevenlabsKey = ttsProvider === 'elevenlabs'
    ? await question('ElevenLabs API Key: ')
    : '';

  console.log('\n🌐 App Configuration');
  const appUrl = await question('App URL (default: http://localhost:3000): ') || 'http://localhost:3000';
  const port = await question('Port (default: 3000): ') || '3000';

  // Build .env content
  let envContent = `# DevForge IDE Configuration
# Generated by setup-env.js
# DO NOT COMMIT THIS FILE - Contains sensitive API keys

# AI Provider Configuration
AI_PROVIDER=${provider}
`;

  if (groqKey) envContent += `GROQ_API_KEY=${groqKey}\n`;
  if (hfKey) envContent += `HUGGINGFACE_API_KEY=${hfKey}\n`;
  if (openrouterKey) envContent += `OPENROUTER_API_KEY=${openrouterKey}\n`;
  if (togetherKey) envContent += `TOGETHER_API_KEY=${togetherKey}\n`;

  envContent += `
# AI Model Selection
AI_MODEL=${model}

# TTS Configuration
TTS_PROVIDER=${ttsProvider}
`;
  if (elevenlabsKey) envContent += `ELEVENLABS_API_KEY=${elevenlabsKey}\n`;

  envContent += `
# App Configuration
APP_URL=${appUrl}
PORT=${port}
`;

  // Write .env file
  fs.writeFileSync(envPath, envContent);

  console.log('\n✅ .env file created successfully!');
  console.log(`\n📄 Location: ${envPath}`);
  console.log('\n🎉 Setup complete! You can now run:');
  console.log('   npm install');
  console.log('   npm run dev');
  console.log('\n');

  rl.close();
}

setupEnv().catch((error) => {
  console.error('❌ Error during setup:', error);
  rl.close();
  process.exit(1);
});
